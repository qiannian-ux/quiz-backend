def esc(s):
    """SQL 字符串转义：单引号翻倍。MySQL 默认不把反斜杠当转义符，别乱加。"""
    return str(s).replace("'", "''")


def j(obj):
    """Python 对象 -> JSON 字符串 -> SQL 安全字面量。"""
    return esc(json.dumps(obj, ensure_ascii=False))


