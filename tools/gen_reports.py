    w("INSERT INTO `dimension` (`id`,`quiz_id`,`code`,`name`,`pair_code`,`pair_order`) VALUES")
    w(',\n'.join(
        "(%d,%d,'%s','%s','%s',%d)" % (did, DISC_QUIZ_ID, code, name, pair, order)
        for did, code, name, pair, order in DISC_DIMENSIONS
    ) + ';')
    w('')

    # ---------- question + question_option ----------
    w('-- 题目（%d 道，四选一）' % len(DISC_QUESTIONS))
    dim_id = {code: did for did, code, _, _, _ in DISC_DIMENSIONS}
    order_codes = ['D', 'I', 'S', 'C']
    qid = 200  # MBTI 占用了 2~94，DISC 从 200 开始，留足空间
    for idx, (text, opts) in enumerate(DISC_QUESTIONS, start=1):
        w("INSERT INTO `question` (`id`,`quiz_id`,`content`,`sort_order`,`status`) VALUES "
          "(%d,%d,'%s',%d,1);" % (qid, DISC_QUIZ_ID, esc(text), idx))
        rows = []
        for pos, code in enumerate(order_codes):
            rows.append("(%d,'%s',%d,1,%d)" % (qid, esc(opts[pos]), dim_id[code], pos))
        w("INSERT INTO `question_option` (`question_id`,`content`,`dimension_id`,`score`,`sort_order`) VALUES")
        w(',\n'.join(rows) + ';')
        qid += 1
    w('')

    # ---------- quiz_result ----------
    w('-- 结果类型（4 型，含初级 + 高级双档解析）')
    for i, code in enumerate(order_codes, start=1):
        d = DISC_TYPES[code]
        basic, advanced = build_report(d)
        w("INSERT INTO `quiz_result` (`quiz_id`,`type_code`,`name`,`summary`,`detail`,`image_url`,`traits`,`basic_report`,`advanced_report`,`sort_order`) VALUES")
        traits = {'strengths': d['strengths'], 'weaknesses': d['weaknesses'], 'careers': d['career']}
        w("(%d,'%s','%s','%s','%s','','%s','%s','%s',%d);" % (
            DISC_QUIZ_ID, esc(code), esc(d['name']), esc(d['one_liner']),
            esc(d['one_liner']),
            esc(json.dumps(traits, ensure_ascii=False)),
            j(basic), j(advanced), i))
    w('')

    io.open(OUT_DISC, 'w', encoding='utf-8').write('\n'.join(out))
    print('已生成:', OUT_DISC)
    print('DISC 题目数:', len(DISC_QUESTIONS), ' 选项数:', len(DISC_QUESTIONS) * 4, ' 结果型数:', len(order_codes))


