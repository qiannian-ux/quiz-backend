# 通用：李克特量表测评生成器（九型 / 霍兰德 / 恋爱依恋 共用）
# =============================================================================
def gen_likert_quiz(quiz_id, code, name, subtitle, desc, emoji, tag, sort_order,
                    dims, statements, types, model):
    """生成一份「李克特五点量表」测评全套数据。

    dims:      [(id, code, name, pair_code, pair_order), ...]  一行 = 一个类型维度
    statements: dict code -> [陈述句...]                         每型若干题，题全指向该 type 维度
    types:      dict code -> 类型定义（含双档解析）
    model:     'MAX'（取最高分类型）或 'TOP3'（取前三拼码，如 RIASEC）
    """
    out = []
    w = out.append
    total_q = sum(len(v) for v in statements.values())
    out_path = os.path.join(DOCS, 'seed-%s.sql' % code)
    title = {'MAX': '累加取最高分类型', 'TOP3': '累加取前三拼码'}[model]

    w('-- =============================================================================')
    w('-- 探我趣测 · %s（全套数据）' % name)
    w('-- 由 tools/gen_reports.py 生成，请勿手改（改脚本后重跑）')
    w('-- -----------------------------------------------------------------------------')
    w('-- 算分模型：scoring_model = %s —— %s。' % (model, title))
    if model == 'TOP3':
        w('--   结果不是预存的单行，而是按得分取前三的类型码拼成三字母（如 RIA/SEC）；')
        w('--   本文件 quiz_result 仍按 6 个类型维度各存一行（含双档解析），')
        w('--   后端取前三维后，把对应三行的报告组合返回即可。')
    w('-- 题型：李克特五点量表，%d 道陈述题，' % total_q)
    w('--       选项 非常不同意(1 分) → 非常同意(5 分)，全部指向同一个类型维度。')
    w('-- 用法：mysql ... < docs/seed-%s.sql（开头清 quiz_id=%d 再重插，可重复执行）' % (code, quiz_id))
    w('-- =============================================================================')
    w('')
    w('SET NAMES utf8mb4;')
    w('')
    w('-- 先删子表再删父表，避免残留孤儿数据')
    w('DELETE FROM `question_option` WHERE `question_id` IN (SELECT `id` FROM `question` WHERE `quiz_id` = %d);' % quiz_id)
    w('DELETE FROM `question`        WHERE `quiz_id` = %d;' % quiz_id)
    w('DELETE FROM `quiz_result`     WHERE `quiz_id` = %d;' % quiz_id)
    w('DELETE FROM `dimension`       WHERE `quiz_id` = %d;' % quiz_id)
    w('DELETE FROM `quiz`            WHERE `id`      = %d;' % quiz_id)
    w('')

    w('-- 测评本体（scoring_model = %s）' % model)
    w("INSERT INTO `quiz` (`id`,`code`,`name`,`subtitle`,`description`,`emoji`,`tag`,`sort_order`,`question_count`,`price_coin`,`scoring_model`,`status`) VALUES")
    w("(%d,'%s','%s','%s','%s','%s','%s',%d,0,0,'%s',1);" % (
        quiz_id, code, name, subtitle, desc, emoji, tag, sort_order, model))
    w('')

    w('-- 类型维度（MAX/TOP3 模型下 dimension 一行 = 一个结果类型，pair_code 统一 TYPE）')
    w("INSERT INTO `dimension` (`id`,`quiz_id`,`code`,`name`,`pair_code`,`pair_order`) VALUES")
    w(',\n'.join(
        "(%d,%d,'%s','%s','%s',%d)" % (did, quiz_id, c, n, pair, order)
        for did, c, n, pair, order in dims
    ) + ';')
    w('')

    w('-- 题目（%d 道，李克特五点量表）' % total_q)
    dim_id = {c: did for did, c, _, _, _ in dims}
    qid = quiz_id * 100  # MBTI 1->100+ 已占；DISC 2->200；九型 3->300；霍兰德 4->400；依恋 5->500
    sort = 1
    for c in statements:
        for stmt in statements[c]:
            w("INSERT INTO `question` (`id`,`quiz_id`,`content`,`sort_order`,`status`) VALUES "
              "(%d,%d,'%s',%d,1);" % (qid, quiz_id, esc(stmt), sort))
            rows = ["(%d,'%s',%d,%d,%d)" % (qid, esc(LIKERT[i]), dim_id[c], i + 1, i)
                    for i in range(len(LIKERT))]
            w("INSERT INTO `question_option` (`question_id`,`content`,`dimension_id`,`score`,`sort_order`) VALUES")
            w(',\n'.join(rows) + ';')
            qid += 1
            sort += 1
    w('')

    w('-- 结果类型（含初级 + 高级双档解析）')
    order = 1
    for c in statements:
        d = types[c]
        basic, advanced = build_report(d)
        traits = {'strengths': d['strengths'], 'weaknesses': d['weaknesses'], 'careers': d['career']}
        w("INSERT INTO `quiz_result` (`quiz_id`,`type_code`,`name`,`summary`,`detail`,`image_url`,`traits`,`basic_report`,`advanced_report`,`sort_order`) VALUES")
        w("(%d,'%s','%s','%s','%s','','%s','%s','%s',%d);" % (
            quiz_id, esc(c), esc(d['name']), esc(d['one_liner']), esc(d['one_liner']),
            esc(json.dumps(traits, ensure_ascii=False)), j(basic), j(advanced), order))
        order += 1
    w('')

    io.open(out_path, 'w', encoding='utf-8').write('\n'.join(out))
    print('已生成:', out_path)
    print('%s 题目数:%d 选项数:%d 结果型数:%d' % (name, total_q, total_q * 5, len(types)))


