def build_report(type_def):
    """把一条类型定义拆成 basic_report / advanced_report 两个 JSON。"""
    basic = {
        'one_liner': type_def['one_liner'],
        'traits': type_def['traits'],
        'strengths': type_def['strengths'],
        'weaknesses': type_def['weaknesses'],
        'tip': type_def['tip'],
    }
    advanced = {
        'chapters': [{'title': t, 'content': c} for t, c in type_def['chapters']],
        'career': type_def['career'],
        'famous': type_def['famous'],
    }
    return basic, advanced


